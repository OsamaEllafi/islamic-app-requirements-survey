/**
 * Source of truth: islamic_app_requirements_questionnaire_ar.md
 *
 * Every section, question, option and the original numbering are preserved
 * verbatim. Authoring notes addressed to the development team (the
 * "ملاحظات مقترحة عند إنشاء النموذج" block) are implemented as behaviour —
 * conditional questions, the 5–7 cap on question 32 — rather than shown to the
 * respondent.
 *
 * NOTE ON IDS: option ids are generated positionally (`q12-o3`). Reordering or
 * removing an option therefore invalidates previously saved answers. If that
 * becomes necessary, bump STORAGE_VERSION in hooks/useAutosave.ts.
 */

/** Authoring shorthand: a trailing `*` marks a free-text ("أخرى") option. */
type RawOption = string;

interface RawQuestion {
  number: number;
  type: QuestionType;
  text: string;
  hint?: string;
  required?: boolean;
  options?: RawOption[];
  maxSelections?: number;
  emphasis?: boolean;
  placeholder?: string;
  conditionalVisibility?: Question['conditionalVisibility'];
}

function buildOptions(questionId: string, raw: RawOption[] | undefined): Option[] | undefined {
  if (!raw) return undefined;
  return raw.map((label, index) => {
    const allowsCustomText = label.endsWith('*');
    return {
      id: `${questionId}-o${index + 1}`,
      label: allowsCustomText ? label.slice(0, -1) : label,
      ...(allowsCustomText ? { allowsCustomText: true } : {}),
    };
  });
}

function buildQuestion(raw: RawQuestion): Question {
  const id = `q${raw.number}`;
  const { options, ...rest } = raw;
  return { ...rest, id, options: buildOptions(id, options) };
}

